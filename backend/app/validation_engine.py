SEVERITY_ORDER = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}


def _check(label, status, actual, expected, ref, severity):
    return {"label": label, "status": status, "actual": actual, "expected": expected, "ref": ref, "severity": severity}


def _check_min(label, value, minimum, unit, ref, severity="CRITICAL"):
    if value is None:
        return _check(label, "MISSING", "—", f"≥ {minimum}{unit}", ref, severity)
    passed = value >= minimum
    return _check(label, "PASS" if passed else "FAIL", f"{value}{unit}", f"≥ {minimum}{unit}", ref, severity)


def _check_max(label, value, maximum, unit, ref, severity="HIGH"):
    if value is None:
        return _check(label, "MISSING", "—", f"≤ {maximum}{unit}", ref, severity)
    passed = value <= maximum
    return _check(label, "PASS" if passed else "FAIL", f"{value}{unit}", f"≤ {maximum}{unit}", ref, severity)


def _check_between(label, value, minimum, maximum, unit, ref, severity="CRITICAL"):
    if value is None:
        return _check(label, "MISSING", "—", f"{minimum}–{maximum}{unit}", ref, severity)
    passed = minimum <= value <= maximum
    return _check(label, "PASS" if passed else "FAIL", f"{value}{unit}", f"{minimum}–{maximum}{unit}", ref, severity)


def _title_case(s):
    s = str(s).strip()
    return s[:1].upper() + s[1:].lower() if s else s


def _check_equals(label, value, expected, ref, severity="CRITICAL"):
    """Fix per review item C17 (Ghee/Butter): a categorical/pass-fail lab
    result (Baudouin Test, presence of β-sitosterol) rather than a numeric
    threshold — mirrors validation.js's checkEquals(). Comparison is
    case-insensitive so "Negative"/"negative" both match the UI's
    lowercase select values."""
    expected_text = _title_case(expected)
    if value is None or value == "":
        return _check(label, "MISSING", "—", expected_text, ref, severity)
    passed = str(value).strip().lower() == str(expected).strip().lower()
    return _check(label, "PASS" if passed else "FAIL", _title_case(value), expected_text, ref, severity)


def _check_micro_count(name, value, limit, ref):
    unit = limit["unit"]
    if value is None:
        return _check(f"{name} ({unit})", "MISSING", "—", f"≤ {limit['m']}", ref, "HIGH")
    if value <= limit["m"]:
        return _check(f"{name} ({unit})", "PASS", value, f"≤ {limit['m']} (m)", ref, "HIGH")
    if limit["M"] is not None and value <= limit["M"]:
        return _check(f"{name} ({unit})", "WARNING", value,
                       f"≤ {limit['m']} (m) — between acceptable ({limit['m']}) and rejection ({limit['M']}) limit",
                       ref, "HIGH")
    # Fix per review item B1 — sign-off received (escalate to CRITICAL):
    # mirrors the JS engine's fix. A confirmed breach is CRITICAL
    # regardless of whether the organism uses a 2-class (ceiling only) or
    # 3-class (warning band + rejection limit) sampling plan — a HIGH
    # severity here used to let a single confirmed E. coli/Staph aureus
    # result over the limit render as WARNING instead of FAIL.
    expected = f"≤ {limit['M']} (M, rejection limit)" if limit["M"] is not None else f"≤ {limit['m']}"
    return _check(f"{name} ({unit})", "FAIL", value, expected, ref, "CRITICAL")


def _check_micro_presence(name, detected, limit, ref):
    if detected is None:
        return _check(name, "MISSING", "—", f"Absent {limit['unit']}", ref, "CRITICAL")
    return _check(name, "FAIL" if detected else "PASS", "Detected" if detected else "Absent",
                   f"Absent {limit['unit']}", ref, "CRITICAL")


def _run_microbiology(category_id: str, lab: Dict[str, Any]) -> Optional[List[dict]]:
    """Fix per review item C17 (bring not-live categories live,
    composition-only): returns None — not an empty list — when this
    category has no MICRO_LIMITS entry yet, mirroring validation.js's
    runMicrobiology(). Lets validate_submission() below tell "no panel
    exists" apart from "the panel exists and everything passed."""
    limits = MICRO_LIMITS.get(category_id)
    if not limits:
        return None
    checks = []
    # Routes by each entry's own "presence" flag, not by table section —
    # mirrors validation.js's runMicrobiology(). Ghee/Butter (Sr.6) and
    # Yogurt/Dahi (Sr.12) list E. coli in Table 2A as "Absent/g", a
    # presence/absence test, not a CFU count with an m/M band.
    for key, limit in limits["table_2a"].items():
        checker = _check_micro_presence if limit.get("presence") else _check_micro_count
        checks.append(checker(limit["name"], lab.get(key), limit, "Appendix B, Table 2A"))
    # Same presence-vs-count routing as Table 2A above — found while
    # smoke-testing the new Dried Ice Cream Mix sub-types (which share
    # Milk Powder's Sr.7 bucket): Milk Powder's own Table 2B carries
    # Bacillus cereus and Sulphite Reducing Clostridia as real CFU counts
    # with m/M bands (500/1000 and 50/100), not presence/absence tests
    # like Salmonella/Listeria — but this loop was running every Table 2B
    # entry through the presence checker unconditionally, so a real count
    # like "400 CFU/g" (well under the 500 acceptable limit) was being
    # read as "Detected" and forced to FAIL. Pre-existing bug in the
    # already-live Milk Powder category, not something introduced by Ice
    # Cream — fixed here since Dried Ice Cream Mix inherits the same bucket.
    for key, limit in limits["table_2b"].items():
        checker = _check_micro_presence if limit.get("presence") else _check_micro_count
        checks.append(checker(limit["name"], lab.get(key), limit, "Appendix B, Table 2B"))
    return checks


def _run_labelling(category_id: str, label: Dict[str, Any]) -> List[dict]:
    """Same cross-engine parity fix as _aggregate_status()/_section_status()
    above: an unticked label element used to be graded "FAIL" outright,
    with no MISSING state at all — unlike validation.js's runLabelling(),
    whose comment is explicit that a checkbox left unticked means "not yet
    declared," not "wrong" (very normal for a product still being
    formulated, before packaging artwork exists). Now MISSING here too, so
    a half-finished label checklist gets the same honest "still some
    things to finish" verdict from either engine. `elements` is looked up
    generically from LABEL_ELEMENTS_ALL/LABEL_ELEMENTS_BY_CATEGORY by
    category_id, so this is unchanged for every category, live or future."""
    elements = LABEL_ELEMENTS_ALL + LABEL_ELEMENTS_BY_CATEGORY.get(category_id, [])
    checks = []
    for el in elements:
        declared = bool(label.get(el["key"]))
        checks.append(_check(el["label"], "PASS" if declared else "MISSING",
                              "Declared" if declared else "Not yet declared", "Declared",
                              "Labelling & Display Regs 2020", el["severity"]))
    return checks


def _run_milk_composition(inp: Dict[str, Any]) -> List[dict]:
    spec = MILK_TYPES.get(inp.get("milk_type"))
    if not spec:
        return []
    checks = []
    # Fix mirroring the JS engine's skimmed-milk fix (D1 / the frontend
    # engine's "the skimmed-milk fix" note in dairyBible.js): this used
    # to add a *second*, redundant "Milk Fat max" check whenever
    # min_fat == 0, on top of the _check_between check just above it —
    # double-counting the same constraint (worse, at a different default
    # severity: HIGH from the duplicate vs CRITICAL from the between
    # check) in both the report and the Formulation Lab's severity-
    # weighted score. The `between` check already covers a 0-to-max
    # range correctly on its own; the extra branch was never needed.
    # This bug was already fixed on the JS side in an earlier pass —
    # the Python engine had drifted and still had it.
    if "max_fat" in spec:
        checks.append(_check_between(f"Milk Fat ({spec['name']})", inp.get("fat"), spec["min_fat"], spec["max_fat"], "%", spec["ref"]))
    else:
        checks.append(_check_min(f"Milk Fat ({spec['name']})", inp.get("fat"), spec["min_fat"], "%", spec["ref"]))
    checks.append(_check_min("SNF (Solids-Not-Fat)", inp.get("snf"), spec["min_snf"], "%", spec["ref"]))

    sodium = inp.get("sodium")
    if sodium is not None:
        checks.append(_check_max("Sodium", sodium, MILK_CROSS_CUTTING["max_sodium_mg_per_100g_snf"]["value"],
                                  " mg/100g SNF", MILK_CROSS_CUTTING["max_sodium_mg_per_100g_snf"]["ref"], "HIGH"))
    urea = inp.get("urea")
    if urea is not None:
        checks.append(_check_max("Urea", urea, MILK_CROSS_CUTTING["max_urea_ppm"]["value"],
                                  " ppm", MILK_CROSS_CUTTING["max_urea_ppm"]["ref"], "MEDIUM"))
    return checks


def _run_paneer_composition(inp: Dict[str, Any]) -> List[dict]:
    spec = PANEER_TYPES.get(inp.get("paneer_type"))
    if not spec:
        return []
    checks = [_check_max(f"Moisture ({spec['name']})", inp.get("moisture"), spec["max_moisture"], "%", spec["ref"], "HIGH")]
    if "max_fat_dry" in spec and "min_fat_dry" in spec:
        checks.append(_check_between("Milk Fat (dry basis)", inp.get("fat"), spec["min_fat_dry"], spec["max_fat_dry"], "%", spec["ref"]))
    elif "max_fat_dry" in spec:
        checks.append(_check_max("Milk Fat (dry basis)", inp.get("fat"), spec["max_fat_dry"], "%", spec["ref"]))
    else:
        checks.append(_check_min("Milk Fat (dry basis)", inp.get("fat"), spec["min_fat_dry"], "%", spec["ref"]))
    return checks


def _run_mozzarella_composition(spec: Dict[str, Any], inp: Dict[str, Any]) -> List[dict]:
    """Fix per review item C17 follow-up — mirrors validation.js's
    runMozzarellaComposition(). See the "computed" comment on
    CHEESE_TYPES["mozzarella"] in dairy_bible.py for the source table."""
    raw_fat = inp.get("fat")
    raw_moisture = inp.get("moisture")
    moisture_type = "high_moisture" if inp.get("moisture_type") == "high_moisture" else "low_moisture"
    type_label = "High moisture" if moisture_type == "high_moisture" else "Low moisture"
    floor = MOZZARELLA_FDM_FLOOR[moisture_type]

    if raw_fat is None or raw_moisture is None or raw_moisture >= 100:
        return [
            _check("Fat in Dry Matter (FDM)", "MISSING", "—", f"≥ {floor}% FDM ({type_label} Mozzarella)", spec["ref"], "CRITICAL"),
            _check("Moisture (Mozzarella)", "MISSING", "—", "Depends on the FDM band — enter Milk Fat and Moisture to see it", spec["ref"], "HIGH"),
        ]

    fat = float(raw_fat)
    moisture = float(raw_moisture)
    fdm = (fat / (100 - moisture)) * 100

    floor_check = _check("Fat in Dry Matter (FDM)", "PASS" if fdm >= floor else "FAIL",
                          f"{fdm:.1f}%", f"≥ {floor}% FDM ({type_label} Mozzarella)", spec["ref"], "CRITICAL")

    band = next((b for b in MOZZARELLA_FDM_BANDS if b["min_fdm"] <= fdm < b["max_fdm"]), None)
    if band is None:
        return [floor_check, _check(
            "Moisture (Mozzarella)", "MISSING", f"{moisture}%",
            "FDM is outside the Compositional Standards Table-2 range (18–85%) — double-check the entered fat/moisture",
            spec["ref"], "HIGH",
        )]
    min_dry_matter = band["high_dm"] if moisture_type == "high_moisture" else band["low_dm"]
    max_moisture = 100 - min_dry_matter
    qualifier_note = f" — {band['qualifier']} classification" if band["qualifier"] else ""
    moisture_check = _check(
        "Moisture (Mozzarella)", "PASS" if moisture <= max_moisture else "FAIL",
        f"{moisture}%", f"≤ {max_moisture:.1f}% (min dry matter {min_dry_matter}%{qualifier_note})",
        spec["ref"], "HIGH",
    )
    return [floor_check, moisture_check]


def _run_cheese_composition(inp: Dict[str, Any]) -> List[dict]:
    spec = CHEESE_TYPES.get(inp.get("cheese_type"))
    if not spec:
        return []
    if spec.get("computed") == "mozzarella_fdm":
        return _run_mozzarella_composition(spec, inp)
    checks = [_check_max(f"Moisture ({spec['name']})", inp.get("moisture"), spec["max_moisture"], "%", spec["ref"], "HIGH")]
    basis_label = "Milk Fat (dry basis)" if spec["fat_basis"] == "dry" else "Milk Fat (as-is basis)"
    checks.append(_check_min(basis_label, inp.get("fat"), spec["min_fat"], "%", spec["ref"]))
    # Fix per review item C17 follow-up: `max_lactose` is back for
    # Processed Cheese — see the CHEESE_TYPES comment in dairy_bible.py.
    # Optional: only added to the report when the FBO actually entered a
    # value, mirroring milk's sodium/urea treatment.
    lactose = inp.get("lactose")
    if "max_lactose" in spec and lactose is not None:
        checks.append(_check_max("Lactose", lactose, spec["max_lactose"], "%", spec.get("lactose_ref", spec["ref"]), "MEDIUM"))
    return checks


def _run_fields(fields: List[dict], spec_name: str, inp: Dict[str, Any]) -> List[dict]:
    """Fix per review item C17 (bring not-live categories live,
    composition-only): generic walker over an explicit fields list —
    mirrors validation.js's runFields()/runFieldCheck(). Extracted out of
    _run_generic_field_composition() (which walks a whole *_TYPES[...]
    entry's fields) so _run_milk_cross_reference_composition() below can
    also call it directly on a partial fields list (Plain Dahi's own
    protein/acidity fields, plus a second call for the milk-cross-
    referenced fat/snf fields) without a second copy of this loop."""
    checks = []
    for field in fields:
        raw = inp.get(field["key"])
        present = raw is not None and raw != ""
        # Optional fields (Ghee's quality-factor tests, milk powder's
        # sodium note) that were never answered don't produce a row at
        # all — same treatment as milk's sodium/urea and cheese's
        # lactose. Required fields always produce a row (MISSING if
        # unanswered).
        if field.get("optional") and not present:
            continue
        label = field["report_label"].replace("{name}", spec_name)
        if field["rule"] == "equals":
            value = raw if present else None
        else:
            value = float(raw) if present else None
        if field["rule"] == "min":
            checks.append(_check_min(label, value, field["min"], field["unit"], field["ref"], field["severity"]))
        elif field["rule"] == "max":
            checks.append(_check_max(label, value, field["max"], field["unit"], field["ref"], field["severity"]))
        elif field["rule"] == "equals":
            checks.append(_check_equals(label, value, field["equals"], field["ref"], field["severity"]))
        else:
            checks.append(_check_between(label, value, field["min"], field["max"], field["unit"], field["ref"], field["severity"]))
    return checks


def _run_generic_field_composition(type_table: Dict[str, Any], subtype_key: str, inp: Dict[str, Any]) -> List[dict]:
    """Whole-schema walk: looks up the matched sub-type's own `fields`
    list and runs it through _run_fields(). Shared by Ghee/Butter, Milk
    Powder, and every ordinary Yogurt/Dahi sub-type (see the long comment
    on GHEE_TYPES in dairy_bible.py for why these categories use a
    generic field list instead of the flat, hand-written keys every
    older *_composition function in this file reads)."""
    spec = type_table.get(inp.get(subtype_key))
    if not spec:
        return []
    return _run_fields(spec["fields"], spec["name"], inp)


