# Fix per the cross-engine parity review (checks/check-engine-parity.mjs):
# this used to escalate a MISSING check straight to FAIL whenever its
# severity was CRITICAL — e.g. an unfinished submission with a required
# lab field not yet entered. That directly contradicted this engine's own
# frontend counterpart, validation.js's aggregateStatus(), whose comment
# is explicit about why: "FAIL is reserved for something that was
# actually tested/declared and came back non-compliant. A MISSING check
# — a lab test not yet run, a label element not yet finalized — means
# 'not done yet,' not 'wrong.'" Identical input used to produce a yellow
# "Warning — still some things to finish" in the browser and a red "FAIL
# / release blocked" from this same function on the API side. Rewritten
# to match validation.js's aggregateStatus() exactly: MISSING (at any
# severity) escalates only as far as WARNING, never FAIL, on its own.
# Driven entirely by each check's `status`/`severity` fields — no
# category id appears here — so this applies unchanged to every category,
# live today or added later.
def _aggregate_status(all_checks: List[dict]) -> str:
    failed = [c for c in all_checks if c["status"] == "FAIL"]
    missing = [c for c in all_checks if c["status"] == "MISSING"]
    critical_failures = [c for c in failed if c["severity"] == "CRITICAL"]
    high_failures = [c for c in failed if c["severity"] == "HIGH"]
    if critical_failures or len(high_failures) >= 3:
        return "FAIL"
    if high_failures or missing or any(c["status"] == "WARNING" for c in all_checks):
        return "WARNING"
    return "PASS"


# Same fix, section-level: mirrors validation.js's sectionStatus() exactly
# now — a MISSING check (any severity) caps a section at WARNING, never
# forces it to FAIL. Also category-agnostic by construction.
def _section_status(checks: List[dict]) -> str:
    if any(c["status"] == "FAIL" for c in checks):
        return "FAIL"
    if any(c["status"] in ("WARNING", "MISSING") for c in checks):
        return "WARNING"
    return "PASS"


_SCORE_WEIGHT = {"CRITICAL": 3, "HIGH": 2, "MEDIUM": 1, "LOW": 1}


def score_formulation(category_id: str, inp: Dict[str, Any]) -> Dict[str, Any]:
    """Formulation Lab scoring: how close a *planned* formulation is to
    compliant, using only the numbers the FBO has entered themselves — no
    lab report exists yet at this stage, so only composition checks run
    (microbiology and label checks need real test/label data and are not
    part of a pre-lab formulation draft). See PLATFORM_PLAN_V2.md §2.5.

    Returns a 0-100 closeness score (severity-weighted pass rate) and a
    gap summary of what's failing or still missing, so a user comparing
    iterations can see exactly what to change.
    """
    if category_id == "milk":
        checks = _run_milk_composition(inp)
    elif category_id == "paneer":
        checks = _run_paneer_composition(inp)
    elif category_id == "cheese":
        checks = _run_cheese_composition(inp)
    elif category_id == "ghee":
        checks = _run_ghee_composition(inp)
    elif category_id == "milk_powder":
        checks = _run_milk_powder_composition(inp)
    elif category_id == "yogurt":
        checks = _run_yogurt_composition(inp)
    elif category_id == "ice_cream":
        checks = _run_ice_cream_composition(inp)
    elif category_id == "khoa":
        checks = _run_khoa_composition(inp)
    elif category_id == "flavoured_milk":
        checks = _run_flavoured_milk_composition(inp)
    elif category_id == "evaporated_milk":
        checks = _run_evaporated_milk_composition(inp)
    elif category_id == "sweetened_condensed_milk":
        checks = _run_sweetened_condensed_milk_composition(inp)
    elif category_id == "cream":
        checks = _run_cream_composition(inp)
    elif category_id == "dairy_whitener":
        checks = _run_dairy_whitener_composition(inp)
    elif category_id == "whey_powder":
        checks = _run_whey_powder_composition(inp)
    elif category_id == "casein_products":
        checks = _run_casein_products_composition(inp)
    elif category_id == "edible_lactose":
        checks = _run_edible_lactose_composition(inp)
    elif category_id == "milk_protein_concentrate":
        checks = _run_milk_protein_concentrate_composition(inp)
    elif category_id == "whey_protein_concentrate":
        checks = _run_whey_protein_concentrate_composition(inp)
    elif category_id == "colostrum_products":
        checks = _run_colostrum_products_composition(inp)
    elif category_id == "dairy_permeate_powders":
        checks = _run_dairy_permeate_powders_composition(inp)
    else:
        checks = []

    if not checks:
        return {"score": 0, "gap_summary": [{"label": "Product type", "issue": "Select a valid product sub-type to score this iteration."}]}

    total_weight = sum(_SCORE_WEIGHT.get(c["severity"], 1) for c in checks)
    passed_weight = sum(_SCORE_WEIGHT.get(c["severity"], 1) for c in checks if c["status"] == "PASS")
    score = round((passed_weight / total_weight) * 100) if total_weight else 0

    gap_summary = [
        {"label": c["label"], "issue": f"{c['actual']} — needs {c['expected']}", "severity": c["severity"], "ref": c["ref"]}
        for c in checks
        if c["status"] != "PASS"
    ]
    return {"score": score, "gap_summary": gap_summary}


