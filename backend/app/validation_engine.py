def _run_milk_cross_reference_composition(spec: Dict[str, Any], inp: Dict[str, Any]) -> List[dict]:
    """Renamed from _run_dahi_composition() when Flavoured Milk (FSS
    2.1.3, Item 2(c)) turned out to need the exact same mechanism as
    Plain Dahi (FSS 2.1.13, Item 2(c)(iii)) — both regulations say the
    product's own Milk Fat/SNF minimums ARE whichever milk it's made
    from, so both reuse MILK_TYPES's already-sourced numbers (this
    file's flat "min_fat"/"max_fat"/"min_snf" keys, not a `fields` list
    — see the YOGURT_TYPES comment in dairy_bible.py for that shape
    divergence) instead of duplicating them, per your "cross-reference
    Milk live" sign-off. Mirrors validation.js's
    runMilkCrossReferenceComposition() (itself renamed from
    runDahiComposition()). The function body is unchanged from the
    Dahi-only version — it was already fully generic — only the name and
    the MISSING-case wording changed. Plain Dahi additionally has its own
    Fermented Milk protein/acidity minimums (Item 2(c)(ii)) as ordinary
    `fields`, run through _run_fields() first; Flavoured Milk's `fields`
    list is empty (FSS 2.1.3, Item 2 states no other composition
    requirement), so that call is a no-op for it."""
    general_checks = _run_fields(spec["fields"], spec["name"], inp)
    milk_spec = MILK_TYPES.get(inp.get("milk_type"))
    if not milk_spec:
        return general_checks + [
            _check("Milk Fat (same as source milk)", "MISSING", "—", "Select which milk this product was made from", spec["ref"], "CRITICAL"),
            _check("SNF (same as source milk)", "MISSING", "—", "Select which milk this product was made from", spec["ref"], "CRITICAL"),
        ]
    raw_fat = inp.get("fat")
    fat_value = float(raw_fat) if raw_fat is not None and raw_fat != "" else None
    if "max_fat" in milk_spec:
        milk_checks = [_check_between(f"Milk Fat ({milk_spec['name']})", fat_value, milk_spec["min_fat"], milk_spec["max_fat"], "%", milk_spec["ref"])]
    else:
        milk_checks = [_check_min(f"Milk Fat ({milk_spec['name']})", fat_value, milk_spec["min_fat"], "%", milk_spec["ref"])]
    raw_snf = inp.get("snf")
    snf_value = float(raw_snf) if raw_snf is not None and raw_snf != "" else None
    milk_checks.append(_check_min("SNF (Solids-Not-Fat)", snf_value, milk_spec["min_snf"], "%", milk_spec["ref"]))
    return general_checks + milk_checks


